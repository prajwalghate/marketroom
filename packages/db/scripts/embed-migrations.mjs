/**
 * Embed drizzle-kit's SQL migrations into a TypeScript module.
 *
 * The app applies migrations at startup. Reading them from `drizzle/` at
 * runtime would tie every deployment to a file-tracing rule; a module is
 * bundled like any other code.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'drizzle/meta/_journal.json'), 'utf8'));

const entries = journal.entries.map((entry) => {
  const text = readFileSync(join(root, 'drizzle', `${entry.tag}.sql`), 'utf8');
  const statements = text
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: entry.tag, statements };
});

const out = `// Generated by scripts/embed-migrations.mjs from drizzle/ — do not edit.
// Change src/schema.ts, then run \`pnpm --filter @marketroom/db generate\`.

export interface Migration {
  readonly tag: string;
  readonly statements: readonly string[];
}

export const MIGRATIONS: readonly Migration[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(root, 'src/migrations.ts'), out);
console.log(`Embedded ${entries.length} migration(s).`);
